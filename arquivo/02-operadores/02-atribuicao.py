# 1. atribuição simples (=)
x = 10
print("x valor inicial: ", x)

# 2. atribuição reduzida adição (+=)
x += 5
print("após x += 5 ", 15)

# 3. atribuição reduzida subtração (-=)
x -= 3
print("após x -= 3: ", x)

# 4. atribuição reduzita mutiplicação (*=)
x *= 2
print("após *= 2 ", x)

# 5. atribuição reduzida divisão (/=)
x /= 3
print("após x /= 3", x)