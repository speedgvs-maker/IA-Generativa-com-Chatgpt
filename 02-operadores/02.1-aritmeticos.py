# operações simples da matemática
a = 10
b = 3

print("soma: ",a + b)
print("subtração: ",a - b)
print("multplicação: ",a * b)
print("divisão float: ",a / b)
print("divisão inteira: ",a // b)
print("exponênciação: ",a ** b)

c = a // b 
print("Verificando o valor do c como float: ", float(c))

